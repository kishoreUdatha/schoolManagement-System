def norm(html: str) -> str:
    """Serialise through one parser so two spellings of the same markup match."""
    soup = BeautifulSoup(html, "html.parser")
    for c in soup.find_all(string=lambda x: isinstance(x, Comment)):
        c.extract()
    return re.sub(r"\s+", " ", str(soup)).strip()


def inner(el: Tag) -> str:
    return "".join(str(c) for c in el.contents)


def write_icons() -> None:
    entries = []
    for name in ICON_NAMES:
        svg = BeautifulSoup(G.icon(name), "html.parser").svg
        ICON_BY_BODY[norm(inner(svg))] = name
        kids = "".join(jsx(c, 3) for c in svg.children)
        entries.append(f"  {name}: (\n    <>\n{kids}    </>\n  ),")
    names = " | ".join(json.dumps(n) for n in ICON_NAMES)
    (WEB / "src/components/ui/Icon.tsx").write_text(
        "// Generated by scripts/build_pages.py from the mock's icon set. Do not edit.\n\n"
        f"export type IconName = {names};\n\n"
        "const PATHS: Record<IconName, JSX.Element> = {\n" + "\n".join(entries) + "\n};\n\n"
        "export function Icon({ name, className = \"\" }: { name: IconName; className?: string }) {\n"
        "  return (\n    <svg viewBox=\"0 0 24 24\" className={`ico ${className}`} fill=\"currentColor\" aria-hidden=\"true\">\n"
        "      {PATHS[name]}\n    </svg>\n  );\n}\n",
        encoding="utf-8",
    )


# ---------------------------------------------------------------- JSX emitter

ATTR = {
    "class": "className", "for": "htmlFor", "tabindex": "tabIndex", "colspan": "colSpan",
    "rowspan": "rowSpan", "maxlength": "maxLength", "minlength": "minLength",
    "autocomplete": "autoComplete", "readonly": "readOnly", "autofocus": "autoFocus",
    "inputmode": "inputMode", "datetime": "dateTime", "viewbox": "viewBox",
    "preserveaspectratio": "preserveAspectRatio", "novalidate": "noValidate",
}
BOOLEAN = {"required", "disabled", "checked", "selected", "readonly", "multiple", "hidden", "autofocus", "novalidate", "open"}
NUMERIC = {"minLength", "maxLength", "tabIndex", "colSpan", "rowSpan", "size", "rows", "cols"}
VOID = {"br", "input", "img", "hr", "meta", "link", "area", "col", "source", "wbr"}
NO_TEXT = {"table", "thead", "tbody", "tfoot", "tr", "select", "colgroup"}


class Ctx:
    """What the page being emitted needs: imports and lifted sample data."""

    def __init__(self, s: dict):
        self.s = s
        self.imports: set[str] = set()
        self.consts: list[str] = []
        self.counter: dict[str, int] = {}

    def const(self, base: str, value: str, comment: str) -> str:
        self.counter[base] = self.counter.get(base, 0) + 1
        name = base if self.counter[base] == 1 else f"{base}{self.counter[base]}"
        self.consts.append(f"// {comment}\nconst {name} = {value};\n")
        return name


CTX: Ctx | None = None


def js(v) -> str:
    """A JS literal; non-breaking spaces stay visible in the source."""
    return json.dumps(v, ensure_ascii=False).replace(chr(0xA0), "\\" + "u00a0")


def camel(name: str) -> str:
    if name in ATTR:
        return ATTR[name]
    if name.startswith(("data-", "aria-")):
        return name
    return re.sub(r"-([a-z])", lambda m: m.group(1).upper(), name)


def style_obj(css: str) -> str:
    parts = []
    for decl in css.split(";"):
        if ":" not in decl:
            continue
        k, v = decl.split(":", 1)
        k, v = k.strip(), v.strip()
        key = js(k) if k.startswith("--") else re.sub(r"-([a-z])", lambda m: m.group(1).upper(), k)
        parts.append(f"{key}: {js(v)}")
    return "{{ " + ", ".join(parts) + " }}"


def href_for(h: str) -> tuple[str, bool]:
    """Map a mock link to an app route. Returns (href, is_internal)."""
    if h in BY_FILE:
        return ROUTE[BY_FILE[h]["id"]], True
    m = re.fullmatch(r"\.\./index\.html(\?.*)?", h)
    if m:
        return "/screens" + (m.group(1) or ""), True
    return h, False


def attrs_of(el: Tag) -> tuple[str, bool]:
    out, internal = [], False
    a = dict(el.attrs)
    # form controls stay uncontrolled so the sample values are just defaults
    if el.name == "input" and a.get("type") not in ("checkbox", "radio") and "value" in a:
        a["defaultValue"] = a.pop("value")
    if el.name == "input" and "checked" in a:
        a.pop("checked")
        a["defaultChecked"] = ""
    if el.name == "select":
        chosen = [o for o in el.find_all("option") if o.has_attr("selected")]
        if chosen:
            o = chosen[-1]
            a["defaultValue"] = o.get("value", o.get_text())
    for k, v in a.items():
        if el.name == "option" and k == "selected":
            continue
        if isinstance(v, list):
            v = " ".join(v)
        if k == "href":
            v, internal = href_for(v)
        elif k in ("data-role-target", "value") and v in BY_FILE:
            v, _ = href_for(v)
        name = camel(k)
        if k in BOOLEAN or k == "defaultChecked":
            out.append(name if v in ("", k) else f"{name}={js(v)}")
        elif k == "style":
            out.append(f"style={style_obj(v)}")
        elif name in NUMERIC and re.fullmatch(r"\d+", v):
            out.append(f"{name}={{{v}}}")
        else:
            out.append(f"{name}={js(v)}")
    return (" " + " ".join(out) if out else ""), internal


def text_jsx(t: str, pad: str, parent: str) -> str:
    if not t:
        return ""
    if not t.strip():
        return "" if parent in NO_TEXT or "\n" in t else f'{pad}{{" "}}\n'
    if t != t.strip() or re.search(r"[{}<>\"'`]|&", t) or chr(0xA0) in t:
        return f"{pad}{{{js(t)}}}\n"
    return f"{pad}{t}\n"


def jsx(node, depth: int, parent: str = "") -> str:
    pad = "  " * depth
    if isinstance(node, Comment):
        return ""
    if isinstance(node, NavigableString):
        return text_jsx(str(node), pad, parent)
    if not isinstance(node, Tag) or node.name == "script":
        return ""
    for try_component in (icon_component, chart_component, art_component, stat_component, panel_component):
        got = try_component(node, depth)
        if got is not None:
            return got
    attrs, internal = attrs_of(node)
    tag = "Link" if node.name == "a" and internal else node.name
    if tag == "Link":
        CTX.imports.add("Link")
    if node.name == "textarea":
        return f"{pad}<textarea{attrs} defaultValue={js(node.get_text())} />\n"
    if node.name in VOID or not node.contents:
        return f"{pad}<{tag}{attrs} />\n"
    kids = children_jsx(node, depth + 1)
    if not kids:
        return f"{pad}<{tag}{attrs} />\n"
    # keep one short text child on the same line
    if len(node.contents) == 1 and isinstance(node.contents[0], NavigableString) and "\n" not in kids.strip() and len(kids.strip()) < 70:
        return f"{pad}<{tag}{attrs}>{kids.strip()}</{tag}>\n"
    return f"{pad}<{tag}{attrs}>\n{kids}{pad}</{tag}>\n"


def children_jsx(el: Tag, depth: int) -> str:
    kids = list(el.children)
    out, i = "", 0
    while i < len(kids):
        got = table_component(kids, i, depth)
        if got is not None:
            out += got[0]
            i += got[1]
            continue
        out += jsx(kids[i], depth, el.name)
        i += 1
    return out


def fragment(nodes: list, depth: int) -> str:
    """Several nodes as one JSX expression (for props like `action`)."""
    pad = "  " * depth
    body = "".join(jsx(n, depth + 1) for n in nodes)
    real = [n for n in nodes if not (isinstance(n, NavigableString) and not str(n).strip())]
    if len(real) == 1 and isinstance(real[0], Tag):
        return jsx(real[0], depth).strip()
    return f"<>\n{body}{pad}</>"


# ---------------------------------------------------------------- components
# Each returns JSX or None. None means "not this component" and the markup is
# emitted as plain JSX instead.

def classes(el: Tag) -> list[str]:
    return [c for c in el.get("class", []) if c] if isinstance(el, Tag) else []


def only_tags(el: Tag) -> list[Tag]:
    """Element children, or None if there is loose text between them."""
    if any(isinstance(c, NavigableString) and str(c).strip() for c in el.children):
        return None
    return [c for c in el.children if isinstance(c, Tag)]


def icon_component(el: Tag, depth: int):
    if el.name != "svg" or "ico" not in classes(el):
        return None
    name = ICON_BY_BODY.get(norm(inner(el)))
    extra = [c for c in classes(el) if c != "ico"]
    if not name or set(el.attrs) - {"viewbox", "class", "fill", "aria-hidden"}:
        return None
    CTX.imports.add("Icon")
    cls = f' className="{" ".join(extra)}"' if extra else ""
    return f'{"  " * depth}<Icon name="{name}"{cls} />\n'


def art_component(el: Tag, depth: int):
    if el.name == "svg" and "hero-art" in classes(el) and norm(str(el)) == norm(G.art()):
        CTX.imports.add("HeroArt")
        return f'{"  " * depth}<HeroArt />\n'
    return None


def chart_component(el: Tag, depth: int):
    if el.name != "svg" or "chart-svg" not in classes(el):
        return None
    kind = "line" if el.find("polyline") else "bar"
    labels = [t.get_text() for t in el.find_all("text") if t.get("text-anchor") == "middle"]
    for args in ((kind, labels), (kind, None)):
        if norm(str(el)) == norm(G.chart(*args)):
            CTX.imports.add("Chart")
            props = (' kind="line"' if kind == "line" else "") + (f" labels={{{js(labels)}}}" if labels != ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat"] else "")
            return f'{"  " * depth}<Chart{props} />\n'
    return None


def stat_component(el: Tag, depth: int):
    if el.name != "div" or "stat-strip" not in classes(el) or set(classes(el)) - {"stat-strip", "compact"}:
        return None
    items = []
    for st in only_tags(el) or []:
        parts = only_tags(st)
        if not parts or len(parts) != 4:
            return None
        items.append((parts[0].get_text(), parts[2].get_text(), parts[3].get_text()))
    if not items:
        return None
    labels, values, notes = map(list, zip(*items))
    compact = "compact" in classes(el)
    if norm(str(el)) != norm(G.stats(labels, values, notes, compact)):
        return None
    CTX.imports.add("StatStrip")
    data = "[\n" + "".join(f"  {{ label: {js(l)}, value: {js(v)}, note: {js(n)} }},\n" for l, v, n in items) + "]"
    name = CTX.const("stats", data, "Headline figures — sample data, replace with the API's summary")
    return f'{"  " * depth}<StatStrip items={{{name}}}{" compact" if compact else ""} />\n'


def panel_component(el: Tag, depth: int):
    if el.name != "section" or classes(el) != ["panel"] or set(el.attrs) != {"class"}:
        return None
    parts = only_tags(el)
    if not parts or len(parts) != 2 or classes(parts[0]) != ["panel-head"] or parts[1].name != "div":
        return None
    head, body = parts
    if set(body.attrs) - {"class"} or classes(body) not in ([], ["panel-body"]):
        return None
    hk = only_tags(head)
    if not hk or hk[0].name != "div" or hk[0].attrs:
        return None
    tk = only_tags(hk[0])
    if not tk or tk[0].name != "h2" or tk[0].attrs or len(tk) > 2 or (len(tk) == 2 and (tk[1].name != "p" or tk[1].attrs)):
        return None
    if any(isinstance(c, Tag) for t in tk for c in t.children):
        return None
    title = tk[0].get_text()
    sub = tk[1].get_text() if len(tk) == 2 else ""
    action_nodes = list(head.children)[1:]
    action_html = "".join(str(n) for n in action_nodes)
    pad = classes(body) == ["panel-body"]
    if norm(str(el)) != norm(G.panel(title, inner(body), sub, action_html, pad)):
        return None
    CTX.imports.add("Panel")
    p = "  " * depth
    props = f"title={js(title)}" + (f" sub={js(sub)}" if sub else "")
    if action_nodes:
        props += f" action={{{fragment(action_nodes, depth + 1)}}}"
    if not pad:
        props += " flush"
    kids = children_jsx(body, depth + 1)
    if not kids:
        return f"{p}<Panel {props} />\n"
    return f"{p}<Panel {props}>\n{kids}{p}</Panel>\n"


