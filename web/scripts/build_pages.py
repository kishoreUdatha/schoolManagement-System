"""Turn the 296 BrightCampus mock screens into Next.js pages.

The mocks ship their own markup (screens/*.html, generated by the designers'
build_screens.py), so each page here is that markup, translated to JSX rather
than redrawn from a PNG. Where the markup is one of the mock's reusable pieces
(a record table, a stat strip, a titled panel, the trend chart, an icon) it
becomes the matching component with its sample data lifted into a constant at
the top of the file; that constant is the thing to replace with an API call.

Every substitution is checked before it is made: the component's arguments are
fed back through the designers' own generator and the result must equal the
original markup, otherwise the markup is kept as plain JSX. So a page can be
less componentised than it might be, but never different from its mock.

    python scripts/build_pages.py [path/to/BrightCampus_296_Editable_Source]

Regenerates src/lib/screens.ts, src/components/ui/Icon.tsx and every page
under src/app/(screens). Hand edits to generated pages are overwritten, so
once a page is wired to the backend its header says so ("// Wired:") and the
converter leaves it alone.
"""
