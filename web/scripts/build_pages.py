def table_component(kids: list, i: int, depth: int):
    """table-wrap + table-empty + table-footer, as the mock's table() emits them."""
    tags = [k for k in kids[i:i + 3]]
    if len(tags) < 3 or not all(isinstance(t, Tag) for t in tags):
        return None
    wrap, empty, foot = tags
    if classes(wrap) != ["table-wrap"] or classes(empty) != ["table-empty"] or classes(foot) != ["table-footer"]:
        return None
    table = wrap.find("table", recursive=False)
    if not table or "data-table" not in classes(table) or not table.thead or not table.tbody:
        return None
    ths = [th.get_text() for th in table.thead.find_all("th")]
    checks = bool(table.thead.find("th", class_="checkcell"))
    action = bool(ths) and ths[-1] == "Action"
    labels = ths[(1 if checks else 0):(len(ths) - 1 if action else len(ths))]
    rows, cells = [], []
    for tr in table.tbody.find_all("tr", recursive=False):
        tds = tr.find_all("td", recursive=False)
        tds = tds[(1 if checks else 0):(len(tds) - 1 if action else len(tds))]
        row, crow = [], []
        for label, td in zip(labels, tds):
            person = td.find("div", class_="person")
            if person:
                box = person.find_all("div", recursive=False)[0]
                name = box.contents[0] if box.contents else ""
                small = box.find("small")
                row.append(str(name))
                crow.append({"name": str(name), "sub": small.get_text()} if small else str(name))
            else:
                row.append(td.get_text())
                crow.append(td.get_text())
        rows.append(row)
        cells.append(crow)
    if not rows:
        return None
    original = "".join(str(t) for t in tags)
    if norm(original) != norm(G.table(CTX.s, labels, rows, len(rows), checks, action)):
        return None
    CTX.imports.add("DataTable")

    def lit(c):
        if isinstance(c, dict):
            return f"{{ name: {js(c['name'])}, sub: {js(c['sub'])} }}"
        return js(c)

    cols = CTX.const("columns", js(labels), "Table columns")
    data = "[\n" + "".join("  [" + ", ".join(lit(c) for c in r) + "],\n" for r in cells) + "]"
    rows_name = CTX.const("rows", data, "Sample records — replace with the API response")
    props = f"columns={{{cols}}} rows={{{rows_name}}}" + ("" if checks else " selectable={false}") + ("" if action else " rowAction={false}")
    return f'{"  " * depth}<DataTable {props} />\n', 3


