def slug(t: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", t.lower()).strip("-")


def route_for(s: dict) -> str:
    if s["id"] == "SCR-001":
        return "/"
    return f"/{slug(MOD_SHORT[s['module']])}/{slug(s['name'])}"


