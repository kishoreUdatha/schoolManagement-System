def legacy_routes() -> dict[str, tuple[str, str]]:
    """Where the old frontend/ implemented each screen, for whoever wires it."""
    audit = REPO / "backend/scripts/screen_audit.tsv"
    out: dict[str, tuple[str, str]] = {}
    if audit.exists():
        for line in audit.read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#"):
                p = line.split("\t")
                if len(p) >= 4:
                    out[p[0]] = (p[3], p[4] if len(p) > 4 else "")
    return out


